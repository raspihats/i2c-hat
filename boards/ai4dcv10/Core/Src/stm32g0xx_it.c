/**
  * @brief This function handles Non maskable interrupt.
  */
void NMI_Handler(void)
{
  /* USER CODE BEGIN NonMaskableInt_IRQn 0 */
  /* The G0 flash raises an NMI on a double ECC error. If it points into the
   * emulated EEPROM area (torn write at power loss), repair the element and
   * continue - the X-CUBE-EEPROM pattern (AN4894). Anything else falls
   * through to the trap below. */
  if (__HAL_FLASH_GET_FLAG(FLASH_FLAG_ECCD))
  {
    uint32_t corrupted = FLASH_BASE + ((FLASH->ECCR & FLASH_ECCR_ADDR_ECC) & ~0x7U);
    if ((corrupted >= START_PAGE_ADDRESS) && (corrupted <= END_EEPROM_ADDRESS))
    {
      __HAL_FLASH_CLEAR_FLAG(FLASH_FLAG_ECCD);
      if (EE_DeleteCorruptedFlashAddress(corrupted) == EE_OK)
      {
        return;
      }
    }
  }
  /* USER CODE END NonMaskableInt_IRQn 0 */
  /* USER CODE BEGIN NonMaskableInt_IRQn 1 */
   while (1)
  {
  }
  /* USER CODE END NonMaskableInt_IRQn 1 */
}

